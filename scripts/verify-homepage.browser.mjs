import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { chromium } from 'playwright';

const base = process.env.HOMEPAGE_PREVIEW_URL || 'http://127.0.0.1:4323';
const output = path.resolve('output/homepage-preview');
const review = path.resolve('.impeccable/review/homepage');
await fs.mkdir(review, { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1050 }, deviceScaleFactor: 1 });
const errors = [], checks = [], demoApiCalls = [];
page.on('pageerror', error => errors.push(error.message));
page.on('request', request => { if (new URL(request.url()).pathname.startsWith('/api/')) demoApiCalls.push({ url: request.url(), method: request.method() }); });
const check = (name, value) => { assert.ok(value, name); checks.push(name); };
const demo = page.locator('#product-demo');
const prepare = page.getByRole('button', { name: 'Prepare example', exact: true });
const submit = page.getByRole('button', { name: 'Submit example', exact: true });
const restart = page.getByRole('button', { name: 'Restart the demonstration' });
const phase = value => page.waitForFunction(value => document.querySelector('#product-demo')?.dataset.phase === value, value);
const ready = async () => { await prepare.waitFor({ state: 'visible' }); await page.waitForFunction(() => !document.querySelector('#product-demo .home-button-primary')?.disabled); };
const open = async () => { await page.goto(base); await page.waitForFunction(() => !document.querySelector('astro-island[component-export="default"]')?.hasAttribute('ssr')); await demo.scrollIntoViewIfNeeded(); };
const capture = async name => {
  await page.evaluate(() => { document.activeElement?.blur(); scrollTo(0, 0); });
  await page.screenshot({ path: path.join(review, name), fullPage: true });
};
const noOverflow = () => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth);
try {
  const response = await page.request.get(base, { maxRedirects: 0 });
  check('Signed-out root serves a public homepage', response.status() === 200 && (await response.text()).includes('From your drawings'));
  check('Session-aware responses remain private', (response.headers()['cache-control'] || '').includes('private, no-store'));
  const signedIn = await page.request.get(base, { headers: { 'x-preview-signed-in': 'yes' }, maxRedirects: 0 });
  check('Signed-in entry still redirects to the dashboard', signedIn.status() === 302 && signedIn.headers().location === '/dashboard');
  for (const query of ['reset=success', 'authError=google_failed', 'returnTo=%2Fprojects']) {
    const response = await page.request.get(`${base}/?${query}`, { maxRedirects: 0 });
    check(`Legacy entry forwards ${query.split('=')[0]} to sign in`, response.status() === 302 && response.headers().location.includes(query));
  }
  await open();
  check('Drawing intake starts before preparation is available', await prepare.isDisabled());
  await ready();
  check('All planning drawings enter automatically', await page.locator('.demo-document-row[data-received="true"]').count() === 3);
  check('Time comparison waits for completion', await page.locator('.demo-time-result').count() === 0);
  await page.getByRole('button', { name: 'Existing floor plan.pdf', exact: false }).click();
  check('Entered drawings can be inspected', (await page.locator('.demo-desktop-drawing .demo-drawing-label').innerText()).includes('Existing drawing'));
  await capture('desktop-drawings.png');
  await prepare.click(); await phase('preparing');
  check('AI activity is visible and early submission is blocked', await page.getByText('Architect Pro is working', { exact: true }).isVisible() && await page.getByRole('button', { name: 'Preparing example…' }).isDisabled());
  await page.waitForFunction(() => document.querySelectorAll('.demo-auto-field[data-filled="true"]').length >= 2);
  check('AI fills fields progressively', await page.locator('.demo-auto-field[data-filled="false"]').count() > 0);
  await capture('desktop-ai-working.png');
  await phase('prepared');
  check('Preparation pauses for the second click', await submit.isEnabled() && await page.locator('.demo-time-result').count() === 0);
  check('AI completes all four fields', await page.locator('.demo-auto-field[data-filled="true"]').count() === 4 && (await page.locator('.demo-prepared-fields').innerText()).includes('Alex Morgan'));
  check('Completion heading receives keyboard focus', await page.locator('.demo-content-heading h3').evaluate(element => element === document.activeElement));
  await capture('desktop-prepared.png');
  await submit.focus(); await page.keyboard.press('Enter'); await phase('submitting');
  check('The second click starts automatic submission', await page.getByRole('button', { name: 'Submitting example…' }).isDisabled());
  await capture('desktop-submitting.png');
  await phase('complete');
  check('Submission completes automatically', await page.getByText('Example submission complete', { exact: true }).first().isVisible());
  check('Result compares 1 minute with 25 minutes', (await page.locator('.demo-time-comparison strong').allTextContents()).join('|') === '1 min|25 min');
  check('Time comparison is labelled illustrative', await page.getByText('Illustrative time comparison. Actual times vary.', { exact: true }).isVisible());
  check('All steps are complete', await page.locator('.demo-step-item[data-complete="true"]').count() === 3);
  check('Final action leads to registration', await page.locator('.demo-action-row a').getAttribute('href') === '/register');
  await capture('desktop-complete.png');
  // Interrupt both timed stages to catch stale callbacks from a previous application.
  await restart.click(); await ready(); await prepare.click(); await phase('preparing');
  await page.getByRole('button', { name: 'Building warrant', exact: true }).click(); await ready();
  check('Type switching resets AI and enters four warrant documents', await page.locator('.demo-document-row[data-received="true"]').count() === 4 && await demo.getAttribute('data-phase') === 'drawings');
  await page.getByRole('button', { name: 'Construction specification.pdf', exact: false }).click();
  check('Specification preview works', await page.locator('.demo-desktop-drawing .demo-specification').isVisible());
  await page.waitForTimeout(3600);
  check('Cancelled preparation cannot advance the new run', await demo.getAttribute('data-phase') === 'drawings');
  await prepare.click(); await phase('prepared');
  check('Warrant preparation uses its own application type', await page.getByText('Building warrant for an extension', { exact: true }).last().isVisible());
  await submit.click(); await phase('submitting'); await restart.click(); await ready(); await page.waitForTimeout(2100);
  check('Restart cancels submission and clears results', await demo.getAttribute('data-phase') === 'drawings' && await page.locator('.demo-time-result').count() === 0);
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.getByRole('button', { name: 'Planning permission', exact: true }).click();
  for (const width of [320, 390, 600, 768, 1024, 1280, 1440, 1600]) {
    await page.setViewportSize({ width, height: 1000 }); await ready();
    check(`${width}px drawings have no horizontal overflow`, await noOverflow());
    await prepare.click(); await phase('prepared');
    check(`${width}px details have no horizontal overflow`, await noOverflow());
    await submit.click(); await phase('complete');
    check(`${width}px result has no horizontal overflow`, await noOverflow());
    if (width === 390) await capture('mobile-complete.png');
    await restart.click();
  }
  await ready();
  check('Reduced motion removes animated movement', await page.locator('.demo-incoming-document').first().evaluate(element => getComputedStyle(element).animationName === 'none'));
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('.demo-mobile-drawing > summary').focus(); await page.keyboard.press('Enter');
  check('Mobile preview opens with the keyboard', await page.locator('.demo-mobile-drawing').getAttribute('open') !== null);
  await page.locator('.demo-mobile-drawing > summary').click();
  await page.locator('.home-faq-list summary').first().focus(); await page.keyboard.press('Enter');
  check('FAQ opens with the keyboard', await page.locator('.home-faq-list details').first().getAttribute('open') !== null);
  await page.locator('.home-faq-list summary').first().click();
  check('Demo makes no API requests', demoApiCalls.length === 0);
  await page.getByRole('link', { name: 'Sign in', exact: true }).first().click();
  await page.getByRole('heading', { name: 'Sign in to Architect Pro' }).waitFor();
  check('Sign in reaches the real form', await page.locator('form[data-action="/api/auth/login"]').count() === 1);
  await open(); await page.getByRole('link', { name: 'Create workspace', exact: true }).click();
  await page.getByRole('heading', { name: 'Create workspace' }).waitFor();
  check('Create workspace reaches registration', await page.locator('form[data-action="/api/auth/register"]').count() === 1);
  await open(); await ready();
  await page.setViewportSize({ width: 1440, height: 1050 }); await page.evaluate(() => { scrollTo(0, 0); return document.fonts.ready; });
  await page.screenshot({ path: path.join(output, 'homepage-desktop.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: path.join(output, 'homepage-mobile.png'), fullPage: true });
  check('No browser runtime errors', errors.length === 0);
  const result = { passed: checks.length, checks, browserErrors: errors, demoApiCalls, preview: base, data: 'Illustrative simulation. No database, uploads, AI calls or submissions.' };
  await fs.writeFile(path.join(output, 'verification.json'), JSON.stringify(result, null, 2));
  console.log(JSON.stringify(result, null, 2));
} finally { await browser.close(); }
