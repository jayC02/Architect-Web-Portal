import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { chromium } from 'playwright';

const base = process.env.HOMEPAGE_PREVIEW_URL || 'http://127.0.0.1:4323';
const output = path.resolve('output/homepage-preview');
const review = path.resolve('.impeccable/review/homepage');
await fs.mkdir(review, { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1050 }, deviceScaleFactor: 1 });
const errors = [], checks = [], demoApiCalls = [];
page.on('pageerror', error => errors.push(error.message));
page.on('request', request => { if (new URL(request.url()).pathname.startsWith('/api/')) demoApiCalls.push({ url: request.url(), method: request.method() }); });
const check = (name, value) => { assert.ok(value, name); checks.push(name); };
const open = async () => { await page.goto(base); await page.getByRole('button', { name: 'Prepare example', exact: true }).waitFor(); await page.waitForFunction(() => !document.querySelector('astro-island[component-export="default"]')?.hasAttribute('ssr')); };
const capture = async (name) => { await page.evaluate(() => { document.activeElement.blur(); scrollTo(0, 0); }); await page.screenshot({ path: path.join(review, name), fullPage: true }); };
try {
  const response = await page.request.get(base, { maxRedirects: 0 });
  check('Signed-out root serves a public homepage', response.status() === 200 && (await response.text()).includes('From your drawings'));
  check('Homepage keeps session-aware responses private', (response.headers()['cache-control'] || '').includes('private, no-store'));
  const signedIn = await page.request.get(base, { headers: { 'x-preview-signed-in': 'yes' }, maxRedirects: 0 });
  check('Signed-in entry still redirects to the dashboard', signedIn.status() === 302 && signedIn.headers().location === '/dashboard');
  for (const query of ['reset=success', 'authError=google_failed', 'returnTo=%2Fprojects']) {
    const response = await page.request.get(`${base}/?${query}`, { maxRedirects: 0 });
    check(`Legacy entry link forwards ${query.split('=')[0]} to sign in`, response.status() === 302 && response.headers().location.startsWith('/login?') && response.headers().location.includes(query));
  }
  await open();
  await page.evaluate(() => document.fonts.ready);
  check('Homepage display font is self-hosted and loaded', await page.evaluate(() => document.fonts.check('600 60px Manrope')));
  check('Example is labelled and does not expose a real file upload', await page.getByText('Sample project and documents. Nothing is uploaded or submitted.').isVisible() && await page.locator('input[type="file"]').count() === 0);
  check('Planning demo starts with three example drawings', await page.locator('.demo-document-row').count() === 3);
  await page.getByRole('button', { name: 'Existing floor plan.pdf Existing drawing', exact: false }).click();
  check('Drawing selection changes the preview', await page.locator('.demo-desktop-drawing .demo-drawing-filename').innerText() === 'Existing floor plan.pdf');
  await page.getByRole('checkbox', { name: 'Include Location plan.pdf', exact: true }).uncheck();
  check('Missing example location plan prevents preparation and explains recovery', await page.getByRole('button', { name: 'Prepare example', exact: true }).isDisabled() && await page.getByText('Include the location and proposed plans to continue.').isVisible());
  await page.getByRole('checkbox', { name: 'Include Location plan.pdf', exact: true }).check();
  await page.getByRole('button', { name: 'Prepare example', exact: true }).click();
  await page.getByRole('heading', { name: 'The details, brought together.' }).waitFor();
  check('Example preparation displays source-backed fields', await page.getByText('24 Willow Road, Glasgow', { exact: true }).first().isVisible() && await page.getByText('From the example location plan').isVisible());
  const proposal = 'Example rear extension with a larger kitchen and dining space.';
  await page.getByRole('textbox', { name: 'Proposal description' }).fill(proposal);
  await capture('desktop-prepared.png');
  await page.getByRole('button', { name: 'Review example', exact: true }).click();
  check('Edited proposal carries through to review', await page.locator('.demo-review-summary > p').innerText() === proposal);
  check('Example review requires explicit confirmation', await page.getByRole('button', { name: 'Finish example review' }).isDisabled());
  for (const name of ['Check the site and applicant details', 'Review the drawings and document types', 'Confirm declarations and any application fees']) await page.getByRole('checkbox', { name, exact: true }).check();
  await page.getByRole('button', { name: 'Finish example review' }).click();
  await page.getByRole('heading', { name: 'Preparation done. Control kept.' }).waitFor();
  check('Finished demo leads to workspace creation', await page.locator('.demo-action-row').getByRole('link', { name: 'Create your workspace' }).getAttribute('href') === '/register');
  await capture('desktop-review.png');
  await page.getByRole('button', { name: 'Back to details', exact: true }).click();
  await page.getByRole('textbox', { name: 'Proposal description' }).fill('');
  check('An empty proposal cannot bypass review using the stepper', await page.locator('.demo-stepper button').nth(2).isDisabled() && await page.getByRole('button', { name: 'Review example', exact: true }).isDisabled());
  await page.getByRole('textbox', { name: 'Proposal description' }).fill('A revised example proposal requiring a fresh review.');
  await page.getByRole('button', { name: 'Review example', exact: true }).click();
  check('Editing a completed proposal clears its review confirmations', await page.locator('.demo-checklist input:checked').count() === 0 && await page.getByRole('button', { name: 'Finish example review' }).isDisabled());
  check('Edited proposal returns to the prepared-for-review state', await page.getByRole('heading', { name: 'Your expertise has the final say.' }).isVisible() && await page.locator('.demo-review-status').innerText() === 'Prepared for review');
  await capture('desktop-review-reset.png');
  await page.getByRole('button', { name: 'Building warrant', exact: true }).click();
  check('Building warrant has its own document set', await page.locator('.demo-document-row').count() === 4 && await page.getByRole('checkbox', { name: 'Include Construction specification.pdf' }).isChecked());
  await page.getByRole('button', { name: 'Construction specification.pdf Specification', exact: false }).click();
  check('Specification can be previewed', await page.locator('.demo-desktop-drawing .demo-specification').isVisible());
  await page.getByRole('button', { name: 'Prepare example', exact: true }).click();
  check('Building warrant preparation uses its own application type', await page.getByText('Building warrant for an extension', { exact: true }).isVisible());
  await page.getByRole('button', { name: 'Restart the demonstration' }).click();
  check('Restart restores the chosen application journey', await page.locator('.demo-document-row').count() === 4 && await page.getByRole('button', { name: 'Prepare example', exact: true }).isVisible());
  await page.getByRole('button', { name: 'Planning permission', exact: true }).click();
  for (const width of [320, 390, 600, 768, 1024, 1280, 1440, 1600]) {
    await page.setViewportSize({ width, height: 1000 });
    check(`${width}px homepage has no horizontal overflow`, await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.getByRole('button', { name: 'Prepare example', exact: true }).click();
    check(`${width}px prepared details have no horizontal overflow`, await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.getByRole('button', { name: 'Review example', exact: true }).click();
    check(`${width}px review has no horizontal overflow`, await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.getByRole('button', { name: 'Restart the demonstration' }).click();
  }
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('.demo-mobile-drawing > summary').focus(); await page.keyboard.press('Enter');
  check('Mobile drawing preview opens with the keyboard', await page.locator('.demo-mobile-drawing').getAttribute('open') !== null);
  await page.locator('.demo-mobile-drawing > summary').click();
  await page.locator('.home-faq-list summary').first().focus(); await page.keyboard.press('Enter');
  check('FAQ opens with the keyboard', await page.locator('.home-faq-list details').first().getAttribute('open') !== null);
  await page.locator('.home-faq-list summary').first().click();
  check('Demo interactions make no API requests', demoApiCalls.length === 0);
  await page.getByRole('link', { name: 'Sign in', exact: true }).first().click();
  await page.getByRole('heading', { name: 'Sign in to Architect Pro' }).waitFor();
  check('Sign-in navigation reaches the real form', await page.locator('form[data-action="/api/auth/login"]').count() === 1);
  await open();
  await page.getByRole('link', { name: 'Create workspace', exact: true }).click();
  await page.getByRole('heading', { name: 'Create workspace' }).waitFor();
  check('Workspace call to action reaches registration', await page.locator('form[data-action="/api/auth/register"]').count() === 1);
  await open();
  await page.emulateMedia({ reducedMotion: 'reduce' });
  check('Demo respects reduced motion', await page.locator('.demo-proposed-lines').first().evaluate(element => getComputedStyle(element).animationName === 'none'));
  await page.setViewportSize({ width: 1440, height: 1050 });
  await page.evaluate(() => document.fonts.ready);
  await capture('desktop.png');
  await page.screenshot({ path: path.join(output, 'homepage-desktop.png'), fullPage: true });
  await page.screenshot({ path: path.join(output, 'homepage-preview.png'), fullPage: false });
  await page.setViewportSize({ width: 390, height: 844 });
  await capture('mobile.png');
  await page.screenshot({ path: path.join(output, 'homepage-mobile.png'), fullPage: true });
  check('No browser runtime errors', errors.length === 0);
  const result = { passed: checks.length, checks, browserErrors: errors, demoApiCalls, preview: base, data: 'Illustrative application demo. No database, uploads, AI calls or submissions.' };
  await fs.writeFile(path.join(output, 'verification.json'), JSON.stringify(result, null, 2));
  console.log(JSON.stringify(result, null, 2));
} finally { await browser.close(); }
