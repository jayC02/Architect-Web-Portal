import { chromium } from 'playwright';
import assert from 'node:assert/strict';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1365, height: 900 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
try {
  await page.goto('http://127.0.0.1:4329');
  await page.getByRole('button', { name: 'Job queue (3)' }).click();
  const cancel = page.getByRole('button', { name: 'Cancel Oak House Rear extension job' });
  await cancel.click();
  await page.getByRole('button', { name: 'Keep job', exact: true }).click();
  assert.equal(await cancel.count(), 1, 'keeping the job preserves the run');
  await cancel.click();
  await page.getByRole('button', { name: 'Cancel job', exact: true }).click();
  await page.getByText('Cancellation requested.', { exact: false }).waitFor();
  const cancelling = page.getByRole('button', { name: 'Cancel Oak House Rear extension job' });
  assert.equal(await cancelling.isDisabled(), true);
  assert.match(await cancelling.innerText(), /Cancelling/);
  assert.equal(await page.getByRole('button', { name: 'Job queue (3)' }).count(), 1, 'running job stays visible until stopped');
  await page.screenshot({ path: 'output/client-applicant-concepts/queue-cancelling-desktop.png' });
  await page.evaluate(async () => { await fetch('/fixture/release'); window.dispatchEvent(new CustomEvent('portal:mutation-success')); });
  await page.getByRole('button', { name: 'Job queue (2)' }).waitFor();
  await page.getByText('Job cancelled. Your prepared application has been kept.', { exact: true }).waitFor();
  assert.equal(await cancelling.count(), 0);
  await page.evaluate(async () => { await fetch('/fixture/claimed'); window.dispatchEvent(new CustomEvent('portal:mutation-success')); });
  await page.getByRole('button', { name: 'Job queue (3)' }).waitFor();
  await cancel.focus();
  await page.keyboard.press('Enter');
  await page.getByRole('button', { name: 'Cancel job', exact: true }).focus();
  await page.keyboard.press('Enter');
  await page.getByRole('button', { name: 'Job queue (2)' }).waitFor();
  assert.equal(await cancel.count(), 0, 'unstarted claim is removed immediately');
  await page.evaluate(async () => { await fetch('/fixture/claimed'); window.dispatchEvent(new CustomEvent('portal:mutation-success')); });
  await page.getByRole('button', { name: 'Job queue (3)' }).waitFor();
  await page.setViewportSize({ width: 390, height: 844 });
  await cancel.click();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  const panel = await page.getByRole('region', { name: 'Agent job queue' }).boundingBox();
  assert(panel.x >= 0 && panel.x + panel.width <= 390);
  await page.screenshot({ path: 'output/client-applicant-concepts/queue-cancellation-mobile.png' });
  await page.keyboard.press('Escape');
  assert.equal(await page.getByRole('region', { name: 'Agent job queue' }).count(), 0);
  assert.equal(await page.getByRole('button', { name: 'Job queue (3)' }).evaluate(button => button === document.activeElement), true);
  assert.deepEqual(errors, []);
  console.log('Browser cancellation passed: keep/cancel, pending stop, release, claimed recovery, keyboard, mobile and focus.');
} finally {
  await browser.close();
}
