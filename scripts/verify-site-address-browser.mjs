import { chromium } from 'playwright';
import assert from 'node:assert/strict';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1365, height: 900 } });
const errors = []; page.on('pageerror', error => errors.push(error.message));
const site = () => page.locator('details.review-section').filter({ has: page.getByText('Site', { exact: true }) });
try {
  await page.goto('http://127.0.0.1:4330/?mode=verified');
  await page.waitForFunction(() => [...document.querySelectorAll('label')].some(label => label.textContent.includes('Local authority') && label.querySelector('input')?.value === 'Glasgow City Council'));
  assert.equal(await site().getByLabel(/Building number/).inputValue(), '105');
  assert.equal(await site().getByLabel(/Address line 1/).inputValue(), 'Ralston Avenue');
  assert.equal(await site().getByLabel(/Postcode/).inputValue(), 'G52 3QH');
  await page.waitForResponse(response => response.url().endsWith('/fixture-verified') && response.request().method() === 'PATCH'
    && JSON.parse(response.request().postData() || '{}').review?.client.postcode === 'G52 3QH');
  const saved = await page.evaluate(async () => (await (await fetch('/inspection')).json()).drafts['fixture-verified'].review);
  assert.equal(saved.site.buildingNumber, '105'); assert.equal(saved.site.addressLine1, 'Ralston Avenue');
  assert.equal(saved.client.postcode, 'G52 3QH'); assert.equal(saved.applicant.postcode, 'G52 3QH');
  console.log('Verified: split fields, postcode/council lookup, autosave, copied client/applicant address');
  await site().getByLabel(/Building number/).fill('106');
  await page.getByText('No exact match found. Confirm the postcode and local authority.').waitFor();
  assert.equal(await site().getByLabel(/Postcode/).inputValue(), '');
  assert.equal(await site().getByLabel(/Local authority/).inputValue(), '');
  console.log('Verified: changing the property clears stale automatic postcode and council');
  const lookupStarted = page.waitForRequest(request => request.url().includes('fixture-race/address-lookup'));
  await page.goto('http://127.0.0.1:4330/?mode=race');
  await lookupStarted;
  await site().getByLabel(/Postcode/).fill('G1 1AA');
  await site().getByLabel(/Local authority/).fill('Architect confirmed council');
  await page.waitForTimeout(3100);
  assert.equal(await site().getByLabel(/Postcode/).inputValue(), 'G1 1AA');
  assert.equal(await site().getByLabel(/Local authority/).inputValue(), 'Architect confirmed council');
  console.log('Verified: late lookup response cannot replace manual postcode/council');
  await page.goto('http://127.0.0.1:4330/?mode=ambiguous');
  await page.getByText('More than one property matches. Confirm the postcode for this site.').waitFor();
  assert.equal(await site().getByLabel(/Postcode/).inputValue(), '');
  console.log('Verified: ambiguous result remains blank with review guidance');
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
  await site().getByLabel(/Postcode/).focus();
  await page.keyboard.type('G52 3QH');
  assert.equal(await site().getByLabel(/Postcode/).inputValue(), 'G52 3QH');
  console.log('Verified: mobile viewport fits, keyboard entry works');
  await page.goto('http://127.0.0.1:4330/?mode=unavailable');
  await page.getByText('Address lookup is temporarily unavailable. You can enter the details below.').waitFor();
  await site().getByLabel(/Postcode/).fill('G52 3QH');
  assert.equal(await site().getByLabel(/Postcode/).inputValue(), 'G52 3QH');
  assert.deepEqual(errors, []);
  console.log('Verified: provider failure leaves editable fields; no browser runtime errors');
} finally { await browser.close(); }
