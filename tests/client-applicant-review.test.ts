import assert from 'node:assert/strict';
import { clientDifferences, exactNameClients, personFromDirectory, selectDirectoryClient, reviewPersonKey } from '../src/lib/clients/application-review';
import { applicationDraftReviewSchema } from '../src/lib/validation/application-draft';
import { evaluateClientApplicationDraftReadiness } from '../src/lib/application-draft-readiness';
import { clientReviewFixture, savedClient } from './fixtures/client-applicant-review';

const review = applicationDraftReviewSchema.parse(clientReviewFixture().review);
const saved = personFromDirectory(savedClient);
assert.equal(reviewPersonKey(saved), reviewPersonKey(Object.fromEntries(Object.entries(saved).reverse()) as typeof saved), 'schema key ordering does not invalidate a pending lookup');
assert.equal(exactNameClients({ ...review.client, displayName: '  LAURA  MACDONALD ' }, [savedClient]).length, 1);
assert.equal(exactNameClients({ ...review.client, displayName: 'MacDonald' }, [savedClient]).length, 0, 'surname alone never links a client');
assert.equal(exactNameClients({ ...review.client, displayName: 'L MacDonald' }, [savedClient]).length, 0, 'initials do not expand to an assumed person');
assert.equal(exactNameClients(review.client, [savedClient, { ...savedClient, id: 'second-laura' }]).length, 2, 'duplicate names remain ambiguous');
assert.deepEqual(clientDifferences({ ...review.client, email: null }, saved), [], 'missing email can come from the saved client');
assert.deepEqual(clientDifferences({ ...review.client, email: 'other@example.test' }, saved), ['email']);
assert.deepEqual(clientDifferences(review.client, { ...saved, email: null }), ['email'], 'saved record must not silently discard a known value');
assert.deepEqual(clientDifferences({ ...review.client, postcode: 'g129dd' }, saved), []);
assert.deepEqual(clientDifferences({ ...review.client, buildingNumber: '99' }, saved, ['buildingNumber']), [], 'inferred site address can be superseded deliberately');
const selected = selectDirectoryClient(review, savedClient);
assert.equal(selected.clientMode, 'existing');
assert.equal(selected.existingClientId, savedClient.id);
assert.equal(selected.clientAddressSameAsSite, false);
assert.deepEqual(selected.client, saved);
assert.deepEqual(selected.applicant, saved, 'same applicant gets the selected client details');
assert.deepEqual(selected.site, review.site, 'client selection does not change the site');
assert.deepEqual(selected.documents, review.documents);
assert.deepEqual(evaluateClientApplicationDraftReadiness(selected), []);
const otherApplicant = { ...review.client, displayName: 'Alex Reid', firstName: 'Alex', lastName: 'Reid' };
assert.deepEqual(selectDirectoryClient({ ...review, applicantDifferentFromClient: true, applicant: otherApplicant }, savedClient).applicant, otherApplicant);
assert.equal(applicationDraftReviewSchema.safeParse({ ...review, client: { ...review.client, email: 'invalid' } }).success, false, 'server schema still rejects invalid email');
assert.ok(evaluateClientApplicationDraftReadiness({ ...review, client: { ...review.client, buildingNumber: null } }).some(issue => issue.key === 'client.buildingNumber'));
console.log('Client/applicant identity, reuse and validation tests passed');
